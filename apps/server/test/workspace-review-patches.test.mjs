import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync, unlinkSync, rmSync, renameSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { workspaceFile, workspaceStatus } from "../dist/git-status.js";

test("working-folder review separates actual staged, unstaged, deleted, and untracked patches", async t => {
  const root = mkdtempSync(join(tmpdir(), "ponderosa-patches-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8" });
  git("init", "-q");
  git("config", "user.name", "Test");
  git("config", "user.email", "test@example.invalid");
  writeFileSync(join(root, "tracked.txt"), "before\n");
  writeFileSync(join(root, "deleted.txt"), "remove me\n");
  git("add", ".");
  git("commit", "-qm", "base");
  writeFileSync(join(root, "tracked.txt"), "staged\n");
  git("add", "tracked.txt");
  writeFileSync(join(root, "tracked.txt"), "working\n");
  unlinkSync(join(root, "deleted.txt"));
  writeFileSync(join(root, "new.txt"), "new\n");
  const tracked = await workspaceFile("project", "agent", "copy", root, "tracked.txt");
  assert.match(tracked.stagedDiff, /-before\n\+staged/);
  assert.match(tracked.unstagedDiff, /-staged\n\+working/);
  assert.equal(tracked.content, "working\n");
  const deleted = await workspaceFile("project", "agent", "copy", root, "deleted.txt");
  assert.equal(deleted.exists, false);
  assert.match(deleted.unstagedDiff, /-remove me/);
  assert.match(deleted.unstagedDiff, /\+\+\+ \/dev\/null/);
  const added = await workspaceFile("project", "agent", "copy", root, "new.txt");
  assert.match(added.unstagedDiff, /--- \/dev\/null/);
  assert.match(added.unstagedDiff, /@@ -0,0 \+1 @@/);
  assert.doesNotMatch(added.unstagedDiff, /\n\+\n/);
  await assert.rejects(workspaceFile("project", "agent", "copy", root, ".env"), /excluded/);
});

test("review handles renames, binary bytes, no-newline files and a repository without HEAD", async t => {
  const root = mkdtempSync(join(tmpdir(), "ponderosa-patch-edge-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8" });
  git("init", "-q"); git("config", "user.name", "Test"); git("config", "user.email", "test@example.invalid");
  writeFileSync(join(root, "new.txt"), "no newline");
  git("add", "new.txt");
  const unborn = await workspaceFile("p", "a", "w", root, "new.txt");
  assert.match(unborn.stagedDiff, /\+no newline\n\\ No newline at end of file/);
  assert.equal(unborn.unstagedDiff, "");
  assert.equal((await workspaceStatus("p", "a", { mode: "shared", rootPath: root }, root)).isGitRepository, true);
  writeFileSync(join(root, "blob.bin"), Buffer.from([0, 255, 1])); git("add", "."); git("commit", "-qm", "base");
  git("mv", "new.txt", "renamed.txt");
  const rename = await workspaceFile("p", "a", "w", root, "renamed.txt");
  assert.match(rename.stagedDiff, /rename from new.txt\nrename to renamed.txt/);
  assert.equal(rename.unstagedDiff, "");
  writeFileSync(join(root, "blob.bin"), Buffer.from([0, 254, 2]));
  const binary = await workspaceFile("p", "a", "w", root, "blob.bin");
  assert.equal(binary.content, undefined);
  assert.match(binary.unstagedDiff, /Binary files a\/blob.bin and b\/blob.bin differ/);
  assert.doesNotMatch(binary.diff, /ponderosa-review-/);
  git("add", "blob.bin");
  const stagedBinary = await workspaceFile("p", "a", "w", root, "blob.bin");
  assert.equal(stagedBinary.unstagedDiff, "", "raw index bytes must compare equal to the working file");
  assert.match(stagedBinary.stagedDiff, /Binary files/);
  git("commit", "-qm", "rename and binary");
  git("rm", "renamed.txt");
  const removed = await workspaceFile("p", "a", "w", root, "renamed.txt");
  assert.match(removed.stagedDiff, /-no newline/);
  assert.equal(removed.exists, false);
  writeFileSync(join(root, "large.txt"), "x".repeat(3 * 1024 * 1024));
  const large = await workspaceFile("p", "a", "w", root, "large.txt");
  assert.equal(large.truncated, true);
});

test("managed separate Git copies preserve real index and working-file bases", async t => {
  const root = mkdtempSync(join(tmpdir(), "ponderosa-patch-worktree-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  git("init", "-q"); git("config", "user.name", "Test"); git("config", "user.email", "test@example.invalid");
  writeFileSync(join(root, "text.txt"), "base\n"); git("add", "."); git("commit", "-qm", "base");
  const copy = join(root, "copy"); git("worktree", "add", "--detach", copy, "HEAD");
  writeFileSync(join(copy, "text.txt"), "working\n");
  const review = await workspaceFile("p", "a", "w", copy, "text.txt");
  assert.match(review.unstagedDiff, /-base\n\+working/);
  assert.equal(review.stagedDiff, "");
  const displaced = join(root, "displaced"); renameSync(copy, displaced);
  writeFileSync(copy, "replacement is not a directory");
  await assert.rejects(workspaceFile("p", "a", "w", copy, "text.txt"), /unavailable|ENOTDIR/);
});
