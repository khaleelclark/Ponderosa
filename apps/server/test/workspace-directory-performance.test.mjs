import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import Fastify from 'fastify';
import { AgentStore, CoordinationV3Store, WorkspaceStore } from '@ponderosa/agents';
import { registerWorkspaceDirectoryRoutes } from '../dist/routes/workspace-directory.js';
import { createServerReadModels } from '../dist/server-read-models.js';

test('ordinary pages bound health to returned rows; summaries preserve scope and fresh status', async t => {
  const dir=mkdtempSync(join(tmpdir(),'ponderosa-directory-check-'));
  const store=new AgentStore(dir), workspace=new WorkspaceStore(dir), coordination=new CoordinationV3Store(store.sqlite), app=Fastify();
  t.after(async()=>{await app.close();store.close();rmSync(dir,{recursive:true,force:true});});
  const projects=[0,1].map(i=>store.createProject({label:`P${i}`,hostPath:`/tmp/P${i}`,defaultEngine:'codex'}));
  const agents=projects.map(p=>{
    const conversation=store.createConversation(p.id,{title:'Chat'});
    return Array.from({length:8},(_,i)=>store.createAgent(p.id,{title:`Agent ${i}`,engine:'codex',conversationId:conversation.id}));
  });
  store.sqlite.prepare('UPDATE agents SET manager_agent_id = ? WHERE id = ?').run(agents[0][0].id,agents[0][7].id);
  const calls=[], status=new Map();
  registerWorkspaceDirectoryRoutes(app,{store,workspace,coordination,projectDisplayPath:p=>p,agentHealth:(scope,rows,options)=>{
    calls.push({scope,ids:rows.map(a=>a.id),options});
    return {scope,generatedAt:new Date().toISOString(),agents:rows.map(a=>({agentId:a.id,childAgentIds:[],status:status.get(a.id)??'idle',reason:'no_active_work',statusTimestamp:'2026-09-10T00:00:00Z'}))};
  }});
  const get=async query=>{calls.length=0;const r=await app.inject(`/api/workspace/directory/agent?${query}`);assert.equal(r.statusCode,200,r.body);return r.json();};
  const first=await get(`projectId=${projects[0].id}&sort=alphabetical&limit=2`);
  assert.equal(first.total,8);assert.equal(calls.flatMap(c=>c.ids).length,2);
  assert.deepEqual(first.items[0].health.childAgentIds,[agents[0][7].id]);
  const next=await get(`projectId=${projects[0].id}&sort=alphabetical&limit=2&cursor=${encodeURIComponent(first.history.cursor)}`);
  assert.equal(next.total,8);assert.equal(calls.flatMap(c=>c.ids).length,2);
  assert.equal(new Set([...first.items,...next.items].map(x=>x.agent.id)).size,4);
  const child=await get(`projectId=${projects[0].id}&search=Agent%207`);
  assert.equal(child.items[0].health.managerAgentId,agents[0][0].id);assert.equal(calls[0].ids.length,1);
  const summary=await get(`projectId=${projects[0].id}&summary=true`);
  assert.equal(summary.total,8);assert.deepEqual(summary.items,[]);assert.equal(calls.length,0);
  status.set(agents[0][0].id,'needs_decision');status.set(agents[1][0].id,'running');
  const active=await get(`projectId=${projects[0].id}&active=true&summary=true`);
  assert.equal(active.total,1);assert.equal(calls.length,1);assert.equal(calls[0].scope.id,projects[0].id);assert.equal(calls[0].options.includeRunHistory,false);
  status.set(agents[0][0].id,'idle');
  assert.equal((await get(`projectId=${projects[0].id}&active=true&summary=true`)).total,0);
  assert.equal((await get('active=true')).activeCount,1);
  const globalPage=await get('limit=2');
  assert.equal(globalPage.total,16);assert.equal(calls.flatMap(c=>c.ids).length,2);
  workspace.updatePreferences({starredResourceIds:[`agent:${agents[0][7].id}`]});
  const starred=await get(`projectId=${projects[0].id}&limit=2`);
  assert.equal(starred.starredItems.length,1);assert.equal(starred.items.length,2);
  assert.equal(calls.flatMap(c=>c.ids).length,3);
});

test('health summary shares live authority without loading coordination history or hiding transitions', async t => {
  const dir=mkdtempSync(join(tmpdir(),'ponderosa-health-check-'));
  const store=new AgentStore(dir), workspace=new WorkspaceStore(dir), coordinationV3=new CoordinationV3Store(store.sqlite);
  t.after(()=>{store.close();rmSync(dir,{recursive:true,force:true});});
  const p=store.createProject({label:'P',hostPath:'/tmp/P',defaultEngine:'codex'});
  const chat=store.createConversation(p.id,{title:'Chat'});
  const agent=store.createAgent(p.id,{title:'Agent',engine:'codex',conversationId:chat.id});
  coordinationV3.agentSnapshot=()=>{throw Error('health must not hydrate full coordination history');};
  const activeRuns=new Map(), scheduledSessionRollovers=new Map();
  const {agentHealth}=createServerReadModels({store,workspace,coordinationV3,activeRuns,scheduledSessionRollovers,managementPlans:new Map(),runtimeStallAfterMs:60_000,reusableRuntime:()=>undefined,transitionRun:()=>true,appendWorkspace:()=>{},publish:()=>{},reconcileCommunicationNotifications:()=>{},reconcileCoordinationAttentionNotifications:()=>{},isClosed:()=>false});
  const scope={type:'project',id:p.id};
  let runReads=0;
  store.getRuns=()=>{runReads++;return [{id:'failed-run',status:'failed',reason:'execution_failed',wakeCause:'human',updatedAt:'2026-09-10T00:00:00Z'}];};
  const read=()=>agentHealth(scope,[agent],{includeRunHistory:false}).agents[0];
  assert.equal(read().status,'idle');assert.equal(runReads,0);
  assert.equal(agentHealth(scope,[agent]).agents[0].assignedWorkOutcome.status,'failed');
  activeRuns.set(agent.id,{startedAt:new Date().toISOString(),executionId:'execution',v3SchedulerRunId:'scheduler',ownershipState:'running'});
  assert.equal(read().status,'running');
  activeRuns.get(agent.id).ownershipState='cancelling';
  assert.equal(read().phase.kind,'stopping');
  activeRuns.get(agent.id).ownershipState='stalled';
  assert.equal(read().status,'stalled');
  activeRuns.get(agent.id).ownershipState='running';
  activeRuns.get(agent.id).leaseExpiresAt='2000-01-01T00:00:00Z';
  assert.equal(read().reason,'execution_lease_expired');
  activeRuns.delete(agent.id);assert.equal(read().status,'idle');
  const decision=workspace.createDecision({projectId:p.id,conversationId:chat.id,agentId:agent.id,question:'Proceed?',options:[],mode:'text',allowOther:true,idempotencyKey:'decision'});
  assert.equal(read().status,'needs_decision');
  assert.equal(workspace.readSince(0).at(-1).event.projectId,p.id);
  workspace.cancelDecision(decision.id);
  assert.equal(read().status,'idle');
  assert.equal(runReads,1);
});
