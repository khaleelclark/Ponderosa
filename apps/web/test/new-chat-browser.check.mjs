import assert from "node:assert/strict";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "node:http";
import { pluginReact } from "@rsbuild/plugin-react";
import { createRsbuild } from "@rsbuild/core";
const root=fileURLToPath(new URL("..",import.meta.url));
const output=await mkdtemp(path.join(tmpdir(),"new-chat-browser-"));
const playwright=await import(process.env.PONDEROSA_PLAYWRIGHT_PATH??"playwright");
const {chromium}=playwright.default??playwright;
let browser,server;
try {
  const build=await createRsbuild({cwd:root,rsbuildConfig:{plugins:[pluginReact()],source:{transformImport:[],entry:{index:path.join(root,"test/new-chat-browser-entry.tsx")}},output:{distPath:{root:output}},logLevel:"error"}});
  await build.build();
  server=createServer(async(req,res)=>{try{const pathname=new URL(req.url,"http://localhost").pathname;const file=path.join(output,!path.extname(pathname)?"index.html":pathname);res.setHeader("Content-Type",file.endsWith(".js")?"text/javascript":file.endsWith(".css")?"text/css":"text/html");res.end(await readFile(file));}catch{res.writeHead(404).end();}}).listen(0,"127.0.0.1");
  await new Promise(resolve=>server.once("listening",resolve));
  browser=await chromium.launch({headless:true,executablePath:process.env.PONDEROSA_CHROMIUM_PATH});
  for(const width of [1440,390,320]) {
    const page=await browser.newPage({viewport:{width,height:900}});
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    const editor=page.locator('[contenteditable="true"]');
    await editor.waitFor();
    assert.equal(await page.getByText("What would you like to work on?").count(),0,"the setup-card prompt is removed");
    assert.equal(await page.evaluate(()=>window.calls.length),0,"Opening composer persists nothing");
    const addButton=page.getByRole("button",{name:"Add attachment or capability"});
    await addButton.focus();
    await addButton.press("Enter");
    const workingFolderAction=page.getByRole("menuitem",{name:/Working folder/});
    await workingFolderAction.focus();
    await workingFolderAction.press("Enter");
    const folderDialog=page.getByRole("dialog",{name:"Choose a Working Folder"});
    await folderDialog.waitFor();
    const currentPath=folderDialog.getByTitle("/home/phoenix");
    const currentPathBox=await currentPath.boundingBox();
    assert.ok(currentPathBox.height<=24,"the narrow picker keeps its current path on one readable line");
    if(width===320) assert.ok(currentPathBox.width>=180,"the 320px picker gives the current path its own row");
    await folderDialog.getByRole("button",{name:"Cancel"}).focus();
    await folderDialog.getByRole("button",{name:"Cancel"}).press("Enter");
    await folderDialog.waitFor({state:"hidden"});
    await page.waitForFunction(()=>document.activeElement?.getAttribute("aria-label")==="Add attachment or capability");
    await addButton.press("Enter");
    await page.getByRole("menuitem",{name:/Working folder/}).click();
    await folderDialog.waitFor();
    await page.getByText("/home/phoenix/repo",{exact:true}).click();
    await page.getByRole("button",{name:"Use This Folder"}).click();
    await folderDialog.waitFor({state:"hidden"});
    await page.getByText(/Working folder:/).waitFor();
    await page.getByRole("button",{name:"Clear working folder"}).waitFor();
    await editor.fill("Keep this exact first message");
    await page.getByRole("button",{name:"Send message",exact:true}).click();
    await page.getByText("Simulated lost response; retry safely",{exact:false}).first().waitFor();
    assert.match(await editor.innerText(),/Keep this exact first message/);
    await page.getByRole("button",{name:"Send message",exact:true}).click();
    await page.waitForFunction(()=>document.body.dataset.created==="true");
    const calls=await page.evaluate(()=>window.calls);
    assert.equal(calls.filter(c=>c.kind==="chat").length,1);
    assert.equal(calls.find(c=>c.kind==="chat").body.hostPath,"/home/phoenix/repo");
    const attempts=calls.filter(c=>c.kind==="agent");
    assert.equal(attempts.length,2);
    assert.equal(attempts[0].options.idempotencyKey,attempts[1].options.idempotencyKey);
    assert.equal(attempts[0].options.title,attempts[1].options.title,"an ambiguous retry retains its chosen custom name");
    assert.notEqual(attempts[0].options.title,"Assistant","new Chats use the configured custom Agent names");
    assert.equal(await page.evaluate(()=>sessionStorage.getItem("ponderosa.new-chat-attempt.v1")),null);
    const clearFolder=page.getByRole("button",{name:"Clear working folder"});
    await clearFolder.focus();
    await clearFolder.press("Enter");
    await page.waitForFunction(()=>document.activeElement?.getAttribute("aria-label")==="Add attachment or capability");
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.close();
  }
  console.log("PASS narrow working-folder layout, focus restoration, selection, and idempotent first-Send retry");
} finally {await browser?.close();server?.close();await rm(output,{recursive:true,force:true});}
