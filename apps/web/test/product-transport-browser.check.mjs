import assert from 'node:assert/strict';
import {mkdtempSync,rmSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {createServer} from 'node:http';
const root=fileURLToPath(new URL('../../../',import.meta.url));
const require=createRequire(join(root,'apps/server/package.json')),webRequire=createRequire(join(root,'apps/web/package.json'));
const {createRsbuild}=await import(pathToFileURL(webRequire.resolve('@rsbuild/core')));
const {chromium}=require('playwright-core');
const {AgentStore,WorkspaceStore,CoordinationV3Store,BranchStore}=await import(pathToFileURL(require.resolve('@ponderosa/agents')));
const {createServer:canonicalServer}=await import(pathToFileURL(join(root,'apps/server/dist/app.js')));
const temp=mkdtempSync(join(tmpdir(),'fast020-client-transport-')),output=join(temp,'web'),store=new AgentStore(join(temp,'data')),coordination=new CoordinationV3Store(store.sqlite),branches=new BranchStore(store.sqlite,coordination);
let browser,server,app;
try {
 const branch=branches.create('Canonical transport','canonical-transport'),project=store.createProject({label:'Branch Chat',hostPath:temp,defaultEngine:'codex',chatOwned:true,branchId:branch.id}),chatId=project.lastConversationId;
 const agent=store.createAgent(project.id,{title:'Branch Agent',engine:'codex',conversationId:chatId});
 const dev=store.createProject({label:'Dev only',hostPath:temp,defaultEngine:'codex'});
 app=canonicalServer({dataDir:join(temp,'data'),store,engines:[],startDrained:true,logger:false,resourceAdmission:{enabled:false}});
 for(const path of [`projects/${project.id}`,`conversations/${chatId}`,`conversations/${chatId}/members`])assert.equal((await app.inject('/api/branches/engine/'+path)).statusCode,200);
 assert.equal((await app.inject(`/api/branches/engine/projects/${dev.id}`)).statusCode,404);
 await(await createRsbuild({cwd:join(root,'apps/web'),rsbuildConfig:{source:{entry:{index:join(root,'apps/web/test/product-transport-browser-entry.ts')}},output:{distPath:{root:output}},logLevel:'error'}})).build();
 server=createServer((req,res)=>{try{const path=new URL(req.url,'http://local').pathname;const file=join(output,path==='/branches'?'index.html':path);res.setHeader('content-type',file.endsWith('.js')?'application/javascript':'text/html');res.end(readFileSync(file))}catch{res.writeHead(404).end()}});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 browser=await chromium.launch({executablePath:process.env.PONDEROSA_CHROMIUM_PATH,headless:true});
 const page=await browser.newPage(),errors=[],requests=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.exposeFunction('canonicalFetch',async(path,init)=>{const reply=await app.inject({url:path,method:init?.method??'GET',...(init?.body?{payload:init.body}:{}),headers:{...(init?.headers??{})}});requests.push({path,status:reply.statusCode});return {body:reply.body,status:reply.statusCode,headers:reply.headers}});
 await page.addInitScript(()=>{window.fetch=async(input,init)=>{const reply=await window.canonicalFetch(String(input),init);return new Response(reply.body,{status:reply.status,headers:reply.headers})}});
 await page.goto(`http://127.0.0.1:${server.address().port}/branches`);
 await page.waitForFunction(()=>typeof window.apiProbe==='function');
 const results=await page.evaluate(ids=>window.apiProbe(ids),{projectId:project.id,chatId,agentId:agent.id,devProjectId:dev.id});
 assert.equal(results.length,4);
 for(const item of results.slice(0,3))assert.equal(item.ok,true,JSON.stringify(item));
 assert.equal(results[3].ok,false);assert.equal(results[3].status,404);
 assert.ok(requests.every(r=>r.path.startsWith('/api/branches/engine/')));
 const transitions=await page.evaluate(ids=>window.cacheProbe(ids),{chatId,projectId:project.id});
 assert.equal(transitions[0].ok,true);assert.equal(transitions[1].ok,false);assert.equal(transitions[1].status,404);
 assert.equal(transitions[2].ok,true);assert.equal(transitions[3].ok,false);assert.equal(transitions[3].status,404);assert.equal(transitions[4].ok,true);
 assert.ok(requests.some(r=>r.path.startsWith('/api/branches/engine/conversations/')&&r.status===200));
 assert.ok(requests.some(r=>r.path.startsWith('/api/conversations/')&&r.status===404));
 const direct=await page.evaluate(ids=>window.directProbe(ids),{projectId:project.id,agentId:agent.id});
 assert.ok(direct.exportUrl.startsWith('/api/branches/engine/agents/'));
 assert.equal(direct.frame.status,404);
 assert.ok(requests.at(-1).path.startsWith('/api/branches/engine/projects/'));
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({requests,results},null,2));
 console.log('PASS actual realApi Branch Project/Chat/member HTTP reads succeed; foreign Dev resource denied.');
} finally {await browser?.close();await new Promise(resolve=>server?server.close(resolve):resolve());app?.prepareForShutdown();await app?.close();store.close();rmSync(temp,{recursive:true,force:true});}
