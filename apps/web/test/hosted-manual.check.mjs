import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { pluginReact } from '@rsbuild/plugin-react';
import { createRsbuild } from '@rsbuild/core';
import Fastify from '../../server/node_modules/fastify/fastify.js';
import { BrowserSessionManager } from '../../server/dist/browser-session-manager.js';
import { startBrowserService, BrowserServiceClient } from '../../server/dist/browser-service.js';
import { chromeBrowserDriverFactory } from '../../server/dist/chrome-cdp-driver.js';
import { registerBrowserRoutes } from '../../server/dist/routes/browsers.js';
import { registerRequestSecurityHooks } from '../../server/dist/server-request-hooks.js';
const { chromium } = await import(process.env.PONDEROSA_PLAYWRIGHT_PATH);
const web = fileURLToPath(new URL('..', import.meta.url));
const root = await mkdtemp(path.join(tmpdir(), 'manual-ui-test-'));
const output = path.join(root, 'web');
const persistent = process.env.PONDEROSA_TEST_BROWSER_SERVICE === '1';
const stateDir = path.join(root, 'state');
const serviceSocket = path.join(root, 'service.sock');
const service = persistent ? await startBrowserService(serviceSocket, stateDir, chromeBrowserDriverFactory(stateDir)) : undefined;
let client = persistent ? new BrowserServiceClient(serviceSocket) : undefined;
if (client) await client.claim();
let latestDriver, forceViewOnly = false;
const factory = client ? (id, _console, _spawned, event, launch) => client.driver(id, event, launch) : chromeBrowserDriverFactory(root);
let manager = new BrowserSessionManager(stateDir, async (...args) => { latestDriver = await factory(...args); return latestDriver; }, () => {});
const managerProxy = new Proxy({}, { get(_target, key) {
  if (key === 'manualDesktopSocket') return (...args) => { const socket = manager.manualDesktopSocket(...args); return forceViewOnly ? latestDriver.manualSocket(true) : socket; };
  const value = manager[key]; return typeof value === 'function' ? value.bind(manager) : value;
} });
const app = Fastify();
registerRequestSecurityHooks(app, { opts: {}, v3DispatchKey: 'fixture', agentMessageCapabilities: new Map(), deletingAgentIds: new Set(), validLauncherSession: () => false, artifactFilesystemError: () => undefined, isArtifactDependentWorkIntake: () => false, isPublicWebAssetRequest: () => false });
const scope = { projectId: 'fixture', agentId: 'project-browser:fixture', runId: 'project:fixture' };
let browser, typed = '', navigated = false, secondNavigated = false;
try {
  const build = await createRsbuild({ cwd: web, rsbuildConfig: { plugins: [pluginReact()], source: { transformImport: [], entry: { index: path.join(web, 'test/hosted-manual-entry.tsx') } }, output: { distPath: { root: output } }, logLevel: 'error' } });
  await build.build();
  registerBrowserRoutes(app, { projectExists: id => id === 'fixture', projectDeletionInProgress: () => false, projectBrowserScope: () => scope, projectBrowserSessions: managerProxy, projectBrowserDto: (_id, value) => value, deleteProjectBrowserGrant: () => {} });
  app.get('/form', async (_request, reply) => { navigated = true; return reply.header('Content-Security-Policy', "default-src 'self'; script-src 'unsafe-inline'").type('text/html').send('<title>Manual fixture</title><input autofocus aria-label="Fixture input" oninput="fetch(\'/typed?value=\'+encodeURIComponent(this.value))">'); });
  app.get('/typed', async request => { typed = request.query.value; return { ok: true }; });
  app.get('/second', async (_request, reply) => { secondNavigated = true; return reply.type('text/html').send('<title>Second tab</title>Separate page'); });
  app.get('/*', async (request, reply) => {
    const pathname = new URL(request.url, 'http://localhost').pathname;
    const file = path.resolve(output, '.' + (pathname === '/' ? '/index.html' : pathname));
    if (!file.startsWith(output + '/')) return reply.code(404).send();
    try { return reply.type(file.endsWith('.js') ? 'text/javascript' : file.endsWith('.css') ? 'text/css' : 'text/html').send(await readFile(file)); } catch { return reply.code(404).send(); }
  });
  await app.listen({ host: '127.0.0.1', port: 0 });
  const origin = `http://127.0.0.1:${app.server.address().port}`;
  browser = await chromium.launch({ headless: true, executablePath: process.env.PONDEROSA_CHROMIUM_PATH });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin);
  await page.getByRole('button', { name: 'Open browser', exact: true }).click();
  await page.locator('[aria-label="Manual Chrome browser"] canvas').waitFor();
  assert.equal(manager.get(scope.agentId).manualControl, 'manual', 'opening the display never attaches automation');
  await page.getByRole('button', { name: 'Browser options', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Browser controls & sign-in', exact: true }).click();
  await page.getByRole('button', { name: 'Done signing in', exact: true }).waitFor();
  const canvas = page.locator('[aria-label="Manual Chrome browser"] canvas');
  await canvas.waitFor();
  await page.getByText('Connecting to your browser…', { exact: true }).waitFor({ state: 'hidden' });
  await page.waitForTimeout(1500);
  const geometry = await canvas.evaluate(element => ({ width: element.width, height: element.height, rect: { width: element.getBoundingClientRect().width, height: element.getBoundingClientRect().height }, parent: { width: element.closest('[aria-label="Manual Chrome browser"]').clientWidth, height: element.closest('[aria-label="Manual Chrome browser"]').clientHeight } }));
  assert.ok(geometry.width >= geometry.rect.width * 1.9, 'native window supplies high-density pixels');
  assert.ok(Math.abs(geometry.rect.height - geometry.parent.height) < 8, `browser fills panel vertically without a fixed-desktop letterbox: ${JSON.stringify(geometry)}`);
  const initial = manager.get(scope.agentId);
  assert.equal(initial.manualControl, 'manual');
  await canvas.click(); await page.keyboard.press('Control+l');
  await page.waitForTimeout(150); // Native Chrome must finish moving focus to its address bar.
  await page.keyboard.type(origin + '/form', { delay: 20 }); await page.keyboard.press('Enter');
  for (let i = 0; i < 100 && !navigated; i++) await page.waitForTimeout(50);
  await page.screenshot({ path: path.join(root, 'hosted-manual-navigation.png') });
  assert.equal(navigated, true, 'native Chrome receives direct navigation input');
  await page.waitForTimeout(500);
  await page.keyboard.type('manual-input-123');
  for (let i = 0; i < 100 && typed !== 'manual-input-123'; i++) await page.waitForTimeout(50);
  assert.equal(typed, 'manual-input-123', 'manual typing is delivered through native desktop');
  await page.getByRole('button', { name: 'Keyboard', exact: true }).click();
  assert.equal(await page.getByRole('textbox', { name: 'Browser mobile keyboard', exact: true }).evaluate(element => element === document.activeElement), true);
  await page.keyboard.insertText(' résumé');
  for (let i = 0; i < 100 && typed !== 'manual-input-123 résumé'; i++) await page.waitForTimeout(50);
  assert.equal(typed, 'manual-input-123 résumé', 'mobile keyboard bridge preserves Unicode');
  await page.keyboard.press('Backspace');
  for (let i = 0; i < 100 && typed !== 'manual-input-123 résum'; i++) await page.waitForTimeout(50);
  assert.equal(typed, 'manual-input-123 résum');
  await page.getByRole('button', { name: 'Let agent work', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Assistant', exact: true }).click();
  await page.getByText(/Enable remote debugging in the owned Chrome window|Chrome could not connect for agent use/).waitFor();
  assert.equal(manager.get(scope.agentId).id, initial.id, 'failed approval does not restart Chrome');
  assert.equal(manager.get(scope.agentId).manualControl, 'manual');
  await canvas.waitFor();
  if (persistent) {
    await manager.closeAll('server_shutdown');
    client = new BrowserServiceClient(serviceSocket);
    const ids = await client.claim();
    manager = new BrowserSessionManager(stateDir, () => assert.fail('reconnect must not launch a replacement'), () => {});
    await manager.restoreRetained(ids, async (id, _console, _spawned, event) => { latestDriver = await client.driver(id, event, undefined, true); return latestDriver; });
  }
  await page.reload();
  await page.getByRole('button', { name: 'Done signing in', exact: true }).waitFor();
  assert.equal(manager.get(scope.agentId).privateSignIn, true, 'private sign-in survives app restart without automatic reconnection');
  await canvas.waitFor();
  await page.getByText('Connecting to your browser…', { exact: true }).waitFor({ state: 'hidden' });
  assert.equal(manager.get(scope.agentId).id, initial.id, 'viewer reconnect keeps the same native browser');
  await page.getByRole('button', { name: 'Keyboard', exact: true }).click();
  await page.keyboard.insertText('-reconnected');
  for (let i = 0; i < 100 && typed !== 'manual-input-123 résum-reconnected'; i++) await page.waitForTimeout(50);
  assert.equal(typed, 'manual-input-123 résum-reconnected', 'unsaved form input survives viewer reconnect and remains editable');
  await manager.openLink(scope, origin + '/second');
  for (let i = 0; i < 100 && !secondNavigated; i++) await page.waitForTimeout(50);
  assert.equal(secondNavigated, true, 'links open directly in the existing native browser');
  await canvas.click(); await page.keyboard.press('Control+Shift+Tab');
  await page.waitForTimeout(250);
  await page.getByRole('button', { name: 'Keyboard', exact: true }).click();
  await page.keyboard.insertText('-after-link');
  for (let i = 0; i < 100 && typed !== 'manual-input-123 résum-reconnected-after-link'; i++) await page.waitForTimeout(50);
  assert.equal(typed, 'manual-input-123 résum-reconnected-after-link', 'opening a link does not overwrite the existing draft tab');
  await page.screenshot({ path: path.join(root, 'hosted-manual-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => {
    const parent = document.querySelector('[aria-label="Manual Chrome browser"]');
    const canvas = parent?.querySelector('canvas');
    return canvas && Math.abs(canvas.getBoundingClientRect().height - parent.clientHeight) < 8;
  }, undefined, { timeout: 10000 });
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: path.join(root, 'hosted-manual-mobile.png') });
  forceViewOnly = true;
  await page.reload();
  await canvas.waitFor();
  await page.getByText('Connecting to your browser…', { exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Keyboard', exact: true }).click();
  // The fixture client still believes it is the operator: enforcement must
  // come from the native view-only server, not just noVNC.viewOnly.
  const beforeReadOnlyInput = typed;
  await page.keyboard.insertText('-must-not-arrive');
  await page.waitForTimeout(600);
  assert.equal(typed, beforeReadOnlyInput, 'native read-only socket rejects input even from a writable client');
  forceViewOnly = false;
  await page.reload();
  await canvas.waitFor();
  await page.getByText('Connecting to your browser…', { exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Keyboard', exact: true }).click();
  await page.keyboard.insertText('-writable-again');
  for (let i = 0; i < 100 && typed !== beforeReadOnlyInput + '-writable-again'; i++) await page.waitForTimeout(50);
  assert.equal(typed, beforeReadOnlyInput + '-writable-again', 'operator stream remains usable after view-only inspection');
  assert.deepEqual(errors, []);
  console.log(`PASS: real native desktop, direct typing/navigation, failed resume preserves browser, unsaved input survives ${persistent ? 'application authority restart' : 'viewer reconnect'}, desktop/mobile layout`);
} finally {
  await browser?.close(); await app.close(); await manager.closeAll('fixture cleanup');
  await service?.close();
  await rm(root, { recursive: true, force: true });
}
